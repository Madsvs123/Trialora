    def has_permission(self, request, view):
        if not request.user or not request.user.is_authenticated:
            return False
        if getattr(view, "allow_unscoped", False) and request.method in SAFE_METHODS:
            return True
        if getattr(view, "allow_unscoped", False) and getattr(view, "auth_open", False):
            return True
        required = getattr(view, "required_permission", None)
        if not required:
            name = getattr(view, "basename", "") or getattr(view, "resource_name", "")
            mapping = self.read_map if request.method in SAFE_METHODS else self.write_map
            required = mapping.get(name)
        if not required:
            return True
        scopes = getattr(request, "api_key_scopes", None)
        if scopes is not None:
            return required in scopes or "*" in scopes
        membership = getattr(request, "membership", None)
        if membership is None:
            return False
        return membership.has_perm(required)
